// ============================================================
// SmsAdapter — 短信适配器接口
//
// SDK 在手机验证码注册/登录时通过此接口发送和校验短信。
// 不提供此适配器则手机号相关功能不可用。
// ============================================================

export interface SmsAdapter {
  /**
   * 发送短信验证码。
   * 由调用方实现具体发送逻辑（阿里云短信、腾讯云短信等）。
   */
  sendCode(params: {
    /** 目标手机号 */
    phone: string;
    /** 验证码 */
    code: string;
  }): Promise<void>;

  /**
   * 校验短信验证码。
   * 由调用方实现具体校验逻辑（通常在服务端 session/缓存中比对）。
   */
  verifyCode(params: {
    /** 目标手机号 */
    phone: string;
    /** 用户提交的验证码 */
    code: string;
  }): Promise<boolean>;
}
